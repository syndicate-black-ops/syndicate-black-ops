"""A suite -> its map (.map), sequence file (.seq) and step file (.steps)."""

from . import mapkit

LOBBY = (-256, -256, 0, 256, 256, 256)
PITCH = 640             # room grid pitch: rooms up to 512 + walls + gap
PER_ROW = 11
ORIGIN_X, ORIGIN_Y = -3500, 512


def layout(suite):
    """Ids and rooms: t01, t02, ... in definition order, on a grid north of the lobby."""
    for i, t in enumerate(suite.tests):
        t.id = 't%02d' % (i + 1)
        sx, sy, sz = t.size
        assert sx <= 512 and sy <= 512 and sz <= 1024, '%s: room larger than 512 x 512' % t.key
        cx = ORIGIN_X + (i % PER_ROW) * PITCH
        cy = ORIGIN_Y + (i // PER_ROW) * PITCH
        t.room = (cx - sx / 2, cy - sy / 2, 0, cx + sx / 2, cy + sy / 2, sz)


def run_tests(suite):
    """Calls each test function: it declares its entities, steps and expectations."""
    for t in suite.tests:
        t.func(t)


def write_map(suite, wad):
    m = mapkit.MapWriter(wad)
    m.add_world(mapkit.shell(*LOBBY))
    for k in range(max(1, suite.players) + 3):
        m.add_ent({'classname': 'info_player_deathmatch', 'origin': '%d %d 36' % (-160 + 80 * (k % 5), -160 + 80 * (k // 5)),
                   'angles': '0 90 0'})
    m.add_ent({'classname': 'light', 'origin': '0 0 200', '_light': '255 255 255 200'})
    for t in suite.tests:
        x0, y0, z0, x1, y1, z1 = t.room
        m.add_world(mapkit.shell(x0, y0, z0, x1, y1, z1))
        m.add_ent({'classname': 'info_target', 'targetname': t.prefix + 'center',
                   'origin': mapkit.fmt_vec(t._abs((0, 0, 36)))})
        for e in t.ents:
            kv = dict(e.kv)
            pos = t._abs(e.at)
            if e.brush is None:
                kv['origin'] = mapkit.fmt_vec(pos)
                m.add_ent(kv)
                continue
            (sx, sy, sz), tex, origin = e.brush
            bx = (pos[0] - sx / 2, pos[1] - sy / 2, pos[2], pos[0] + sx / 2, pos[1] + sy / 2, pos[2] + sz)
            brushes = [mapkit.box(*bx, tex)]
            if origin:
                cx, cy, cz = pos[0], pos[1], pos[2] + sz / 2
                brushes.append(mapkit.box(cx - 4, cy - 4, cz - 4, cx + 4, cy + 4, cz + 4, mapkit.ORIGIN))
            m.add_ent(kv, brushes)
    # entity-lump index of every named entity (0 = worldspawn; the compilers keep the .map's order), for '#@name'
    suite.lump_index = {kv.get('targetname'): i + 1 for i, (kv, _b) in enumerate(m.ents) if kv.get('targetname')}
    return m.text()


def write_seq(suite):
    parts = []
    for t in suite.tests:
        parts += t.seq
    return ('// generated by tests/entity (suite %s)\n\n' % suite.name + '\n'.join(parts)) if parts else None


def write_steps(suite, trace_name, seed=1):
    """The run: players in and in the round, then each test in its room, one after the other."""
    lines = ['// generated by tests/entity (suite %s)' % suite.name,
             'test_trace %s' % trace_name, 'test_seed %d' % seed, 'test_mark suite:start']
    n = max([t.players for t in suite.tests] + [0])
    for k in range(1, n + 1):
        lines += ['test_player add et%d' % k, 'wait_frames 2', 'test_join player%d' % k]
    if n:
        lines += ['wait 0.5', 'test_round start']
        for k in range(1, n + 1):
            lines.append('wait_for alive player%d 20' % k)
    lines += ['wait 0.5', 'test_mark suite:ready']
    for t in suite.tests:
        lines.append('test_mark %s:begin' % t.id)
        for k in range(1, t.players + 1):
            # side by side in the room's south part, facing north
            x0, y0, z0, x1, y1, z1 = t.room
            p = t._abs((-48 + 48 * (k - 1), -(y1 - y0) / 2 + 48, 36))
            lines.append('test_teleport player%d %g %g %g 90' % (k, p[0], p[1], p[2]))
        if t.players:
            lines.append('wait_frames 3')
        lines += t.steps
        # two more frames: thinks due in the last waited frame run after its steps (StartFrame comes first)
        lines += ['wait_frames 2', 'test_mark %s:end' % t.id]
        for k in range(1, t.players + 1):
            lines.append('test_teleport player%d %d %d 36 90' % (k, -160 + 80 * (k % 5), 160))
        lines.append('wait 0.1')
    lines += ['test_mark suite:end', 'test_quit']
    return '\n'.join(lines) + '\n'


def duration(suite):
    return sum(t.duration + 0.5 for t in suite.tests) + 5

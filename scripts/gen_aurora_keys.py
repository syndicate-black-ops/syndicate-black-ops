#!/usr/bin/env python3
"""The in-game particle editor's key table, from the web editor's key list (docs/AURORA.md "Editor").

    scripts/gen_aurora_keys.py            writes src/cl_dll/aurora/aurora_keys.h from
                                          tools/aurora-editor/core/aurora-keys.json
    scripts/gen_aurora_keys.py --check    exit 1 when the header differs from what the list gives

aurora-keys.json is the one list of every .aur key (name, kind, label, default, slider span, step, unit, choices
and their plain names, help, a short tip) for both editors: change the list, then run this. Python 3 standard library only.
"""

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "tools", "aurora-editor", "core", "aurora-keys.json")
OUT = os.path.join(ROOT, "src", "cl_dll", "aurora", "aurora_keys.h")

KINDS = {"int": "AURKEY_INT", "number": "AURKEY_NUMBER", "range": "AURKEY_RANGE", "enum": "AURKEY_ENUM",
         "type": "AURKEY_TYPE", "sprite": "AURKEY_SPRITE", "name": "AURKEY_NAME"}


def c_str(s):
    if s is None:
        return "nullptr"
    out = []
    for ch in str(s):
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ord(ch) < 128:
            out.append(ch)
        else:
            out.append("".join("\\x%02x" % b for b in ch.encode("utf-8")) + '""')
    return '"' + "".join(out) + '"'


def c_float(v):
    text = repr(float(v))
    return text + "f" if "e" in text or "." in text else text + ".0f"


def decimals(step):
    if step is None or float(step) >= 1:
        return 0
    text = ("%.6f" % float(step)).rstrip("0")
    return len(text.split(".")[1]) if "." in text else 0


def entry(k, scope):
    kind = k["kind"]
    if kind not in KINDS:
        raise SystemExit("aurora-keys.json: unknown kind %r of %s" % (kind, k["key"]))
    has_def = "default" in k
    default = k.get("default")
    def_num = default if isinstance(default, (int, float)) and not isinstance(default, bool) else 0
    def_text = None
    if has_def:
        def_text = default if isinstance(default, str) else ("%g" % default)
    ui = k.get("ui", [0, 1])
    limit = k.get("limit")
    step = k.get("step", 1 if kind == "int" else None)
    choices = "|".join(k["choices"]) if "choices" in k else None
    # each choice's plain name ("" when the list gives none: the value itself is shown)
    names = k.get("choiceLabels", {})
    choice_labels = "|".join(names.get(c, "") for c in k["choices"]) if "choices" in k else None
    fields = [
        c_str(k["key"]), KINDS[kind], c_str(k.get("group", scope)), c_str(k["label"]),
        "true" if has_def else "false", c_float(def_num), c_str(def_text),
        c_float(ui[0]), c_float(ui[1]), c_float(step if step is not None else 1), str(decimals(step)),
        c_str(k.get("unit")), c_str(choices), c_str(choice_labels),
        "true" if limit else "false", c_float(limit[0] if limit else 0), c_float(limit[1] if limit else 0),
        c_str(k.get("help", "")), c_str(k.get("tip", "")),
    ]
    return "\t{ " + ", ".join(fields) + " },"


def render(data):
    lines = [
        "// GENERATED by scripts/gen_aurora_keys.py from tools/aurora-editor/core/aurora-keys.json: do not edit.",
        "// Every key SBO's .aur parser reads (particlesys.cpp), as the web editor shows it: the in-game particle editor",
        "// (vgui2/sbo_particle_editor.cpp) builds its rows from these. docs/AURORA.md \"Editor\".",
        "#pragma once",
        "",
        "enum AuroraKeyKind",
        "{",
        "\tAURKEY_INT,\t\t// a whole number",
        "\tAURKEY_NUMBER,\t// a number",
        "\tAURKEY_RANGE,\t// a number or min..max",
        "\tAURKEY_ENUM,\t// one of choices ('|' separated; \"\" = not set)",
        "\tAURKEY_TYPE,\t// a type's name",
        "\tAURKEY_SPRITE,\t// a sprite file",
        "\tAURKEY_NAME,\t// the type's own name",
        "};",
        "",
        "struct AuroraKeyDef",
        "{",
        "\tconst char *key;",
        "\tint kind;\t\t\t\t// AuroraKeyKind",
        "\tconst char *group;\t\t// AURORA_KEY_GROUPS id (\"top\" for the top-level keys)",
        "\tconst char *label;",
        "\tbool hasDefault;\t\t// false: not set unless the script sets it",
        "\tfloat def;\t\t\t\t// the default of a number",
        "\tconst char *defText;\t// the default as the script writes it (nullptr: none)",
        "\tfloat uiMin, uiMax;\t\t// the slider's span (the game has no bound unless hasLimit)",
        "\tfloat step;",
        "\tint decimals;",
        "\tconst char *unit;",
        "\tconst char *choices;",
        "\tconst char *choiceLabels;\t// the choices' plain names, in the same order ('|' separated; \"\" = none)",
        "\tbool hasLimit;",
        "\tfloat limitMin, limitMax;",
        "\tconst char *help;",
        "\tconst char *tip;\t\t\t// one short sentence (the editors' tooltip)",
        "};",
        "",
        "struct AuroraKeyGroup",
        "{",
        "\tconst char *id;",
        "\tconst char *label;",
        "};",
        "",
        "static const AuroraKeyDef AURORA_TOP_KEYS[] = {",
    ]
    lines += [entry(k, "top") for k in data["top"]]
    lines += ["};", "", "static const AuroraKeyGroup AURORA_KEY_GROUPS[] = {"]
    lines += ["\t{ %s, %s }," % (c_str(g["id"]), c_str(g["label"])) for g in data["groups"]]
    lines += ["};", "", "static const AuroraKeyDef AURORA_TYPE_KEYS[] = {"]
    lines += [entry(k, "type") for k in data["type"]]
    lim = data["limits"]
    lines += [
        "};",
        "",
        "#define AURORA_TOP_KEY_COUNT\t((int)( sizeof( AURORA_TOP_KEYS ) / sizeof( AURORA_TOP_KEYS[0] ) ))",
        "#define AURORA_TYPE_KEY_COUNT\t((int)( sizeof( AURORA_TYPE_KEYS ) / sizeof( AURORA_TYPE_KEYS[0] ) ))",
        "#define AURORA_KEY_GROUP_COUNT\t((int)( sizeof( AURORA_KEY_GROUPS ) / sizeof( AURORA_KEY_GROUPS[0] ) ))",
        "#define AURORA_KEYS_MAX_TYPE_NAME\t%d" % lim["maxTypeName"],
        "#define AURORA_KEYS_MAX_TYPES\t%d" % lim["maxTypes"],
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 when the header is not current")
    args = ap.parse_args()
    with open(SRC, encoding="utf-8") as f:
        text = render(json.load(f))
    if args.check:
        try:
            with open(OUT, encoding="utf-8", newline="") as f:
                current = f.read()
        except OSError:
            current = None
        if current != text:
            print("gen_aurora_keys: %s is not current: run scripts/gen_aurora_keys.py" % os.path.relpath(OUT, ROOT))
            return 1
        print("gen_aurora_keys: %s is current" % os.path.relpath(OUT, ROOT))
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("gen_aurora_keys: wrote %s" % os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
